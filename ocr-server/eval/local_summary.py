"""local_summary — batch-level COMBINED parser-drop view for the LOCAL replay loop.

Why this exists
---------------
The AWS run writes  runs/<batch>/SUMMARY.html  = the accuracy summary across all
testsets (study + thin), generated by run_all.py during the run.

The LOCAL replay loop (replay_compare -> parser_drop_classify) instead writes a
PER-TESTSET file  runs/<batch>/<sub>/PARSER_DROP_CLASSIFY[_<dir>].html  in each
testset's own folder. There was no single page combining them, so you had to
open study/ and thin/ (and, at scale, invoice_war/) separately.

This is that combined page — the LOCAL equivalent of SUMMARY.html. It is named
LOCAL_SUMMARY[_<dir>].html so it NEVER collides with the AWS SUMMARY.html that
lives in the same batch folder.

What it does
------------
For each testset subfolder under the batch it (re)runs parser_drop_classify to
refresh that testset's PARSER_DROP_CLASSIFY[_<dir>].json (no OCR — the classifier
just reads compare/ + snapshots/), then merges the per-testset `scores` (KPI) and
`defects` (column x pattern) into one batch-level page.

READ-ONLY sidecar: writes ONLY LOCAL_SUMMARY[_<dir>].html at the batch root and
delegates to parser_drop_classify (itself a sidecar). Touches nothing the checker
reads (samples/, compare/, metrics/, trend).

    ../.venv/Scripts/python.exe eval/local_summary.py
    ../.venv/Scripts/python.exe eval/local_summary.py --batch 053_20260617_142725
    ../.venv/Scripts/python.exe eval/local_summary.py --compare-dir compare   # AWS-run scorecards (수정 전)
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import contract as C  # noqa: E402


def _latest_batch() -> str | None:
    """Most-recent batch dir = a runs/<x>/ holding >=1 subfolder with run_meta.json
    (run_all --all layout). Flat single-testset runs (run_meta directly in <x>/)
    are not batches and are skipped."""
    if not os.path.isdir(C.RUNS_DIR):
        return None
    best, best_m = None, -1.0
    for name in os.listdir(C.RUNS_DIR):
        d = os.path.join(C.RUNS_DIR, name)
        if not os.path.isdir(d):
            continue
        has_sub = any(os.path.isfile(os.path.join(d, s, "run_meta.json"))
                      for s in os.listdir(d) if os.path.isdir(os.path.join(d, s)))
        if not has_sub:
            continue
        m = os.path.getmtime(d)
        if m > best_m:
            best_m, best = m, d
    return best


def _subdirs(batch_dir: str) -> list[str]:
    """Testset subfolder names under the batch (each has a run_meta.json)."""
    return sorted(s for s in os.listdir(batch_dir)
                  if os.path.isfile(os.path.join(batch_dir, s, "run_meta.json")))


def _testset_of(sub_dir: str) -> str:
    try:
        with open(os.path.join(sub_dir, "run_meta.json"), encoding="utf-8") as fh:
            return json.load(fh).get("testset") or C.DEFAULT_TESTSET
    except (OSError, json.JSONDecodeError):
        return C.DEFAULT_TESTSET


def _pick_compare_dir(sub_dir: str, requested: str) -> str | None:
    """Prefer the requested scorecard dir; fall back to the run's own compare/.
    None = neither exists (nothing to classify for this testset)."""
    if os.path.isdir(os.path.join(sub_dir, requested)):
        return requested
    if os.path.isdir(os.path.join(sub_dir, "compare")):
        return "compare"
    return None


def _suffix(compare_dir: str) -> str:
    return "" if compare_dir == "compare" else "_" + compare_dir


def _classify(batch_name: str, sub: str, testset: str, compare_dir: str) -> bool:
    """Run parser_drop_classify for one testset subfolder (refresh its JSON)."""
    rc = subprocess.run(
        [sys.executable, os.path.join(HERE, "parser_drop_classify.py"),
         "--ts", f"{batch_name}/{sub}", "--testset", testset,
         "--compare-dir", compare_dir],
        capture_output=True, text=True, encoding="utf-8",
    ).returncode
    return rc == 0


def _role(testset: str) -> str:
    """study(rich)=회귀 기준점 · thin=학습데이터(+canned이면 실데이터 대기)."""
    try:
        ts = C.get_testset(testset)
    except KeyError:
        return ""
    if ts["kind"] == "rich":
        return "회귀 기준점"
    tag = " <span class='muted'>(실데이터 대기)</span>" if ts["runMode"] == "canned" else ""
    return "학습데이터" + tag


def _pct(match: int, scored: int) -> str:
    return "n/a" if not scored else f"{100 * match / scored:.1f}%"


# parser-drop pattern columns (same taxonomy as parser_drop_classify)
_P = ("drop", "mislocate", "wrongpick")
_PAT_KO = {"drop": "누락(drop)", "mislocate": "오배치(mislocate)", "wrongpick": "오선택(wrongpick)"}


def _render(batch_name: str, compare_dir: str, per: list[dict]) -> str:
    import datetime as _dt
    from trend import _CSS, _esc
    try:
        from report import _FIELD_KO
    except Exception:
        _FIELD_KO = {}

    def ko(col: str) -> str:
        k = _FIELD_KO.get(col)
        return (f"<b>{_esc(k)}</b> <span class='muted' style='font-size:12px'>({_esc(col)})</span>"
                if k else _esc(col))

    gen = _dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    is_replay = compare_dir != "compare"
    src_label = "수정 후 (로컬 replay)" if is_replay else "AWS run 기준 (수정 전)"

    # combined KPI across all testsets
    fS = sum(p["fScored"] for p in per); fM = sum(p["fMatch"] for p in per)
    cS = sum(p["cScored"] for p in per); cM = sum(p["cMatch"] for p in per)
    n_def = sum(p["nDef"] for p in per); n_pd = sum(p["nPd"] for p in per)
    n_rc = sum(p["nRc"] for p in per); n_af = sum(p["nAf"] for p in per)
    rec_pct = (100 * n_pd / n_def) if n_def else 0

    extra = (".kpis{display:flex;flex-wrap:wrap;gap:10px;max-width:1600px;margin:0 auto}"
             ".kpi{flex:1;min-width:130px;background:var(--card);border:1px solid var(--line);"
             "border-radius:10px;padding:12px 16px;box-shadow:0 1px 2px rgba(27,31,36,.04)}"
             ".kpi .lab{color:var(--muted);font-size:12px}.kpi b{font-size:24px;display:block;margin:2px 0}"
             ".kpi .sub{color:var(--muted);font-size:11.5px}"
             ".acc-lo{background:#ffeef0}.acc-mid{background:#fff8e6}.acc-ok{background:#e9f7ec}")

    H = ["<!doctype html><html lang='ko'><head><meta charset='utf-8'>",
         "<meta name='viewport' content='width=device-width,initial-scale=1'>",
         f"<title>로컬 parser-drop 종합 - {_esc(batch_name)}</title><style>", _CSS, extra,
         "</style></head><body>",
         f"<div class='head'><h1>로컬 parser-drop 종합 "
         f"<span class='muted' style='font-size:14px'>({_esc(batch_name)})</span></h1>"
         f"<div class='gen'>생성 {gen} · {_esc(src_label)} · "
         "AWS 정확도 요약은 <a href='SUMMARY.html'>SUMMARY.html</a></div></div>",
         "<div class='note'>"
         "<div class='row'><b>parser-drop</b> = GT 값이 OCR 출력엔 있는데 파서가 떨군 것 "
         "<b>(회수 가능)</b> · <b>recognition</b> = OCR이 글자 자체를 못 읽음(OCR 바운드, 파서 대상 아님)</div>"
         "<div class='row'>각 데이터셋 상세는 <b>상세</b> 링크(testset별 PARSER_DROP_CLASSIFY) 참조. "
         "이 페이지는 study + thin(+실데이터)을 한 번에 보는 로컬 합산뷰.</div></div>"]

    # combined KPI cards
    H.append("<div class='kpis'>"
             f"<div class='kpi'><div class='lab'>전체 필드</div><b>{_pct(fM, fS)}</b>"
             f"<div class='sub'>{fM}/{fS}</div></div>"
             f"<div class='kpi'><div class='lab'>전체 셀</div><b>{_pct(cM, cS)}</b>"
             f"<div class='sub'>{cM}/{cS}</div></div>"
             f"<div class='kpi'><div class='lab'>결함</div><b>{n_def}</b>"
             f"<div class='sub'>불일치+누락</div></div>"
             f"<div class='kpi'><div class='lab'>parser-drop</div><b>{n_pd}</b>"
             f"<div class='sub'>OCR 읽음 · 회수가능 {rec_pct:.0f}%</div></div>"
             f"<div class='kpi'><div class='lab'>ambiguous_fuzzy</div><b>{n_af}</b>"
             f"<div class='sub'>fuzzy-only · pending</div></div>"
             f"<div class='kpi'><div class='lab'>recognition</div><b>{n_rc}</b>"
             f"<div class='sub'>OCR 바운드</div></div></div>")

    def acc_cls(match, scored):
        if not scored:
            return ""
        a = match / scored
        return "acc-lo" if a < 0.5 else ("acc-mid" if a < 0.8 else "acc-ok")

    def acc_td(match, scored):
        return f"<td class='{acc_cls(match, scored)}'>{_pct(match, scored)}</td>"

    def acc_mm(match, scored, macro):
        mi = _pct(match, scored)
        ma = "n/a" if macro is None else f"{macro * 100:.1f}%"
        return f"<td class='{acc_cls(match, scored)}'>{mi} <span class='muted'>/ {ma}</span></td>"

    # per-testset summary table — micro/macro + 분류상세/리포트/비교 링크 (SUMMARY 미러)
    H.append("<section><h2>데이터셋별 요약 <span class='muted'>(필드·셀 = micro / macro)</span></h2>"
             "<table class='sumtable'><thead><tr>"
             "<th>데이터셋</th><th>종류</th><th>건수</th><th>필드</th><th>셀</th>"
             "<th>결함</th><th>parser-drop</th><th>recognition</th>"
             "<th>분류 상세</th><th>상세 리포트</th><th>비교</th>"
             "</tr></thead><tbody>")
    for p in per:
        note = "" if p["hasSnap"] else " <span class='muted' style='font-size:12px'>(스냅샷 없음)</span>"
        detail = (f"<a class='btn' href='{_esc(p['sub'])}/{_esc(p['classifyHtml'])}'>분류</a>"
                  if p["ok"] else "<span class='muted' style='font-size:12px'>분류 실패</span>")
        report = (f"<a class='btn' href='{_esc(p['sub'])}/report.html'>리포트</a>"
                  if p["hasReport"] else "<span class='muted' style='font-size:12px'>없음</span>")
        compare = (f"<a class='btn' style='background:var(--warn);border-color:var(--warn)' "
                   f"href='{_esc(p['sub'])}/compare.html'>비교</a>"
                   if p["hasCompare"] else "<span class='muted' style='font-size:12px'>직전 없음</span>")
        H.append(f"<tr><td>{_esc(p['testset'])} <code>{_esc(p['sub'])}/</code>{note}</td>"
                 f"<td>{_role(p['testset'])}</td><td>{p['n']}건</td>"
                 + acc_mm(p["fMatch"], p["fScored"], p["fMacro"])
                 + acc_mm(p["cMatch"], p["cScored"], p["cMacro"])
                 + f"<td>{p['nDef']}</td><td>{p['nPd']}</td><td>{p['nRc']}</td>"
                 f"<td>{detail}</td><td>{report}</td><td>{compare}</td></tr>")
    H.append("</tbody></table>"
             "<div class='legend'>분류 상세 = testset별 parser-drop 분류(PARSER_DROP_CLASSIFY) · "
             "상세 리포트 = report.html · 비교 = 직전 run 대비 compare.html · "
             "AWS 정확도/게이트 요약은 <a href='SUMMARY.html'>SUMMARY.html</a></div></section>")

    # per-testset parser-drop column x pattern (the actionable axis)
    pat_th = "".join(f"<th>{_PAT_KO[p]}</th>" for p in _P)
    for p in per:
        agg: dict = defaultdict(lambda: defaultdict(int))
        for d in p["pdrops"]:
            agg[d["column"]][d["pattern"]] += 1
        ordered = sorted(agg.items(), key=lambda kv: -sum(kv[1].values()))
        H.append(f"<section><h2>{_esc(p['testset'])} — 컬럼 × 패턴 "
                 f"<span class='muted'>(parser-drop n={p['nPd']})</span></h2>")
        if not ordered:
            empty = ("스냅샷 없음 — 실데이터(이미지+스냅샷) 오면 채워짐"
                     if not p["hasSnap"] else "parser-drop 0건")
            H.append(f"<div class='muted'>{empty}</div></section>")
            continue
        H.append("<table class='sumtable'><thead><tr><th>컬럼</th>" + pat_th
                 + "<th>합계</th></tr></thead><tbody>")
        for col, pats in ordered:
            tot = sum(pats.values())
            H.append(f"<tr><td>{ko(col)}</td>"
                     + "".join(f"<td>{pats.get(pp, 0)}</td>" for pp in _P)
                     + f"<td><b>{tot}</b></td></tr>")
        H.append("</tbody></table></section>")

    # accumulated history — the LOCAL equivalent of SUMMARY's embedded TREND.
    # Each testset's replay_history.json (auto-grown by parser_drop_classify on
    # every replay run) shows the KPI progression edit-over-edit.
    try:
        from replay_summary import _render_rows as _rr
    except Exception:
        _rr = None
    if _rr and any(p["hist"] for p in per):
        H.append("<div class='head' style='margin-top:24px'><h1 style='font-size:17px'>누적 결과 "
                 "<span class='muted' style='font-size:13px'>(replay 돌릴 때마다 자동 누적)</span></h1></div>")
        for p in per:
            if not p["hist"]:
                continue
            H.append(f"<section><h2>{_esc(p['testset'])} <span class='muted'>누적 이력</span></h2>"
                     "<table><thead><tr><th>시각</th><th>셀 정확도</th><th>Δ셀</th><th>필드 정확도</th>"
                     "<th>파서누락</th><th>인식오류</th><th>지어내기</th><th>경로 free/fb</th>"
                     "</tr></thead><tbody>")
            for k, pct, d, fld, paths_s in _rr(p["hist"]):
                if d is None:
                    dcol, dtxt = "var(--muted)", "·"
                else:
                    dcol = "var(--up)" if d > 0 else ("var(--down)" if d < 0 else "var(--muted)")
                    dtxt = f"{d:+.1f}"
                pending = k.get("ambiguous")
                pdrop_text = str(k.get("pdrop")) if pending is None else f"{k.get('pdrop')} (+{pending} pending)"
                H.append(f"<tr><td>{_esc(k.get('ts', ''))}</td><td>{k['cm']}/{k['cs']} ({pct:.1f}%)</td>"
                         f"<td style='color:{dcol}'>{dtxt}</td><td>{_esc(fld)}</td>"
                         f"<td>{pdrop_text}</td><td>{k.get('recog')}</td>"
                         f"<td>{k.get('spur')}</td><td>{_esc(paths_s)}</td></tr>")
            H.append("</tbody></table></section>")

    H.append("</body></html>")
    return "\n".join(H)


def build(batch_dir: str, requested_compare_dir: str, refresh: bool = True) -> str | None:
    """Render the combined LOCAL_SUMMARY for a batch.

    refresh=True  : (re)run parser_drop_classify per testset, then merge (standalone use).
    refresh=False : merge-only — read whatever per-testset JSONs already exist. Used by
                    the parser_drop_classify auto-hook so it never re-invokes the
                    classifier (no recursion); testsets without a JSON are skipped.
    """
    batch_name = os.path.basename(batch_dir.rstrip(os.sep))
    subs = _subdirs(batch_dir)
    if not subs:
        print(f"no testset subfolders in {batch_dir}")
        return None

    per: list[dict] = []
    for sub in subs:
        sub_dir = os.path.join(batch_dir, sub)
        testset = _testset_of(sub_dir)
        cdir = _pick_compare_dir(sub_dir, requested_compare_dir)
        if cdir is None:
            if refresh:
                print(f"  [skip] {sub}: no '{requested_compare_dir}'/ nor 'compare'/")
            continue
        ok = _classify(batch_name, sub, testset, cdir) if refresh else True
        jpath = os.path.join(sub_dir, f"PARSER_DROP_CLASSIFY{_suffix(cdir)}.json")
        try:
            with open(jpath, encoding="utf-8") as fh:
                j = json.load(fh)
        except (OSError, json.JSONDecodeError) as exc:
            print(f"  [skip] {sub}: classifier json unreadable ({exc})")
            continue
        scores = j.get("scores") or []
        defects = j.get("defects") or []
        pdrops = [d for d in defects if d["class"] == "parser_drop"]
        faccs = [s["fieldAcc"] for s in scores if s.get("fieldAcc") is not None]
        caccs = [s["cellAcc"] for s in scores if s.get("cellAcc") is not None]
        hist = []
        hp = os.path.join(sub_dir, "replay_history.json")
        if os.path.isfile(hp):
            try:
                with open(hp, encoding="utf-8") as fh:
                    hist = json.load(fh)
            except (OSError, json.JSONDecodeError):
                hist = []
        per.append({
            "sub": sub, "testset": testset, "cdir": cdir, "ok": ok,
            "hasSnap": j.get("hasSnapshots", False),
            "n": len(scores),
            "fScored": sum(s["fScored"] for s in scores),
            "fMatch": sum(s["fMatch"] for s in scores),
            "cScored": sum(s["cScored"] for s in scores),
            "cMatch": sum(s["cMatch"] for s in scores),
            "fMacro": (sum(faccs) / len(faccs)) if faccs else None,
            "cMacro": (sum(caccs) / len(caccs)) if caccs else None,
            "nDef": len(defects), "nPd": len(pdrops),
            "nRc": sum(1 for d in defects if d["class"] == "recognition"),
            "nAf": sum(1 for d in defects if d["class"] == "ambiguous_fuzzy"),
            "pdrops": pdrops,
            # links that mirror the AWS SUMMARY (상세 리포트 / 비교 / 분류 상세) + 누적 이력
            "hasReport": os.path.isfile(os.path.join(sub_dir, "report.html")),
            "hasCompare": os.path.isfile(os.path.join(sub_dir, "compare.html")),
            "classifyHtml": f"PARSER_DROP_CLASSIFY{_suffix(cdir)}.html",
            "hist": hist,
        })

    if not per:
        print("nothing to summarize (no classifiable testsets)")
        return None

    out = os.path.join(batch_dir, f"LOCAL_SUMMARY{_suffix(requested_compare_dir)}.html")
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(_render(batch_name, requested_compare_dir, per))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", default=None,
                    help="batch dir name under runs/ (default: latest --all batch)")
    ap.add_argument("--compare-dir", default="replay_compare",
                    help="scorecards to summarize: 'replay_compare' (로컬 수정 후, default) "
                         "or 'compare' (AWS run 기준). Per-testset falls back to 'compare' "
                         "if the requested dir is absent.")
    args = ap.parse_args()

    batch_dir = (os.path.join(C.RUNS_DIR, args.batch) if args.batch else _latest_batch())
    if not batch_dir or not os.path.isdir(batch_dir):
        print(f"no batch dir ({batch_dir})")
        return 2

    out = build(batch_dir, args.compare_dir)
    if not out:
        return 1
    print(f"[written] {out}  <- 브라우저로 열기")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
