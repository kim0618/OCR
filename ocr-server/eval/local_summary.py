"""local_summary — batch-level COMBINED parser-drop view for the LOCAL replay loop.

Why this exists
---------------
The AWS run writes  runs/<batch>/SUMMARY.html  = the accuracy summary across all
testsets (study + thin), generated by run_all.py during the run.

The LOCAL replay loop (replay_compare -> parser_drop_classify) instead writes a
PER-TESTSET file  runs/<batch>/<sub>/PARSER_DROP_CLASSIFY[_<dir>].html  in each
testset's own folder. There was no single page combining them, so you had to
open study/ and thin/ (and, at scale, invoice_war/) separately.

This is that combined page — the LOCAL equivalent of SUMMARY.html. It is named
LOCAL_SUMMARY[_<dir>].html so it NEVER collides with the AWS SUMMARY.html that
lives in the same batch folder.

What it does
------------
For each testset subfolder under the batch it (re)runs parser_drop_classify to
refresh that testset's PARSER_DROP_CLASSIFY[_<dir>].json (no OCR — the classifier
just reads compare/ + snapshots/), then merges the per-testset `scores` (KPI) and
`defects` (column x pattern) into one batch-level page.

READ-ONLY sidecar: writes ONLY LOCAL_SUMMARY[_<dir>].html at the batch root and
delegates to parser_drop_classify (itself a sidecar). Touches nothing the checker
reads (samples/, compare/, metrics/, trend).

    ../.venv/Scripts/python.exe eval/local_summary.py
    ../.venv/Scripts/python.exe eval/local_summary.py --batch 053_20260617_142725
    ../.venv/Scripts/python.exe eval/local_summary.py --compare-dir compare   # AWS-run scorecards (수정 전)
"""
from __future__ import annotations

